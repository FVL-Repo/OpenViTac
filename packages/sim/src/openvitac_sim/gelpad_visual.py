# Typing for pxr is not shipped; these calls are runtime-verified.

"""Visual-only gelpad proxy driven by UIPC surface points.

The UIPC soft body lives only in the worker process. This module rewrites the
authored GsMini gelpad ``UsdGeom.Mesh`` topology to the worker's complete rest
surface and publishes every rendered frame's world-space points into that mesh.
It keeps the authored ``Looks/Black`` material; printed marker images are
generated by :mod:`openvitac_sim.sensor.gsmini`, never by this proxy.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any

import numpy as np
from numpy.typing import NDArray
from pxr import Gf, Usd, UsdGeom, Vt


def world_to_local(
    T_world: NDArray[np.floating[Any]],
    world_vertices: NDArray[np.floating[Any]],
) -> NDArray[np.float64]:
    """Map world points into the frame of ``T_world`` (world <- local)."""
    T = np.asarray(T_world, dtype=np.float64).reshape(4, 4)
    points = np.asarray(world_vertices, dtype=np.float64).reshape(-1, 3)
    inverse = np.linalg.inv(T)
    return points @ inverse[:3, :3].T + inverse[:3, 3]


def visual_update_due(step_index: int, every: int, *, recording: bool) -> bool:
    """Whether a render frame should refresh the visual mesh.

    Recorded runs update on the same cadence as the step sink (``every``);
    an unrecorded/live scene updates every step.
    """
    if every <= 0:
        raise ValueError(f"visual cadence must be positive, got {every}")
    if not recording:
        return True
    return step_index % every == 0


def find_gelpad_mesh(stage: Usd.Stage, gelpad_prim_path: str) -> Usd.Prim:
    """Return the authored ``<gelpad_prim_path>/mesh`` Mesh prim.

    GsMini authors the display mesh as a direct child named ``mesh``; use the
    explicit path rather than guessing among descendants.
    """
    path = f"{gelpad_prim_path.rstrip('/')}/mesh"
    prim = stage.GetPrimAtPath(path)
    if not prim.IsValid() or not prim.IsA(UsdGeom.Mesh):
        raise RuntimeError(f"gelpad mesh prim {path!r} is missing or not a Mesh")
    return prim


def mesh_world_transform(mesh_prim: Usd.Prim) -> NDArray[np.float64]:
    """Cached world <- mesh-local transform at the current (reset) time."""
    cache = UsdGeom.XformCache(Usd.TimeCode.Default())
    matrix = cache.GetLocalToWorldTransform(mesh_prim)
    return np.array(
        [[matrix[row][col] for col in range(4)] for row in range(4)],
        dtype=np.float64,
    ).T


def _set_points(mesh: UsdGeom.Mesh, points: NDArray[np.floating[Any]]) -> None:
    local = np.ascontiguousarray(points, dtype=np.float32)
    mesh.GetPointsAttr().Set(Vt.Vec3fArray.FromNumpy(local))
    low = local.min(axis=0)
    high = local.max(axis=0)
    mesh.GetExtentAttr().Set(
        Vt.Vec3fArray(
            [
                Gf.Vec3f(float(low[0]), float(low[1]), float(low[2])),
                Gf.Vec3f(float(high[0]), float(high[1]), float(high[2])),
            ]
        )
    )


def rewrite_mesh_topology(
    mesh_prim: Usd.Prim,
    local_vertices: NDArray[np.floating[Any]],
    triangles: NDArray[np.integer[Any]],
) -> NDArray[np.int32]:
    """Replace the authored display topology with the complete UIPC surface.

    The UIPC boundary includes the near sheet, far/contact sheet, bevels, and
    side walls. Keeping all of it makes the visual proxy a closed black slab
    for head/wrist cameras; the independent sensor pass never edits this mesh.
    """
    vertices = np.asarray(local_vertices, dtype=np.float64).reshape(-1, 3)
    tris = np.asarray(triangles, dtype=np.int32).reshape(-1, 3)
    if vertices.size == 0 or tris.size == 0:
        raise ValueError("gelpad surface must have vertices and triangles")
    if not np.isfinite(vertices).all():
        raise ValueError("gelpad surface vertices must be finite")
    if int(tris.min()) < 0 or int(tris.max()) >= len(vertices):
        raise ValueError("gelpad triangle indices are out of range")

    mesh = UsdGeom.Mesh(mesh_prim)
    # Deformation may flip a grazing triangle; a double-sided closed shell must
    # not develop holes. Material binding is left untouched (authored Black).
    mesh.GetDoubleSidedAttr().Set(True)
    mesh.GetFaceVertexCountsAttr().Set(Vt.IntArray([3] * len(tris)))
    mesh.GetFaceVertexIndicesAttr().Set(
        Vt.IntArray(tris.reshape(-1).astype(np.int32).tolist())
    )
    # The authored asset carries 984-point vertex normals in a referenced layer;
    # Clear() would only reveal that stale value. Author face-varying normals
    # for the new surface so the renderer never mixes topologies.
    corners = vertices[tris]
    face_normals = np.cross(
        corners[:, 1] - corners[:, 0], corners[:, 2] - corners[:, 0]
    )
    lengths = np.linalg.norm(face_normals, axis=1)
    if np.any(lengths == 0.0):
        raise ValueError("gelpad surface has degenerate triangles")
    face_normals = (face_normals / lengths[:, None]).repeat(3, axis=0)
    mesh.GetNormalsAttr().Set(
        Vt.Vec3fArray.FromNumpy(
            np.ascontiguousarray(face_normals, dtype=np.float32)
        )
    )
    mesh.SetNormalsInterpolation(UsdGeom.Tokens.faceVarying)
    mesh.GetSubdivisionSchemeAttr().Set(UsdGeom.Tokens.none)
    _set_points(mesh, vertices)

    # Override referenced motion/UV/topology metadata that no longer matches the
    # UIPC surface. An empty authored array is required: RemoveProperty only
    # removes the local opinion and would expose the referenced 984-point data.
    mesh.GetVelocitiesAttr().Set(Vt.Vec3fArray())
    mesh.GetAccelerationsAttr().Set(Vt.Vec3fArray())
    mesh.GetCornerIndicesAttr().Set(Vt.IntArray())
    mesh.GetCornerSharpnessesAttr().Set(Vt.FloatArray())
    mesh.GetCreaseIndicesAttr().Set(Vt.IntArray())
    mesh.GetCreaseLengthsAttr().Set(Vt.IntArray())
    mesh.GetCreaseSharpnessesAttr().Set(Vt.FloatArray())
    mesh.GetHoleIndicesAttr().Set(Vt.IntArray())
    st = mesh.GetPrim().GetAttribute("primvars:st")
    if st:
        st.Set(Vt.Vec2fArray())
    st_indices = mesh.GetPrim().GetAttribute("primvars:st:indices")
    if st_indices:
        st_indices.Set(Vt.IntArray())
    return np.ascontiguousarray(tris, dtype=np.int32)


@dataclass
class GelpadVisual:
    """One authored gelpad mesh driven by UIPC world-space surface points."""

    side: str
    mesh_prim: Usd.Prim
    T_world_mesh: NDArray[np.float64]
    n_vertices: int

    @classmethod
    def bind(
        cls,
        *,
        side: str,
        gelpad_prim_path: str,
        rest_vertices: NDArray[np.floating[Any]],
        triangles: NDArray[np.integer[Any]],
        stage: Usd.Stage,
    ) -> GelpadVisual:
        """Rewrite the proxy once at reset and cache its world transform."""
        prim = find_gelpad_mesh(stage, gelpad_prim_path)
        T_world = mesh_world_transform(prim)
        rest = np.asarray(rest_vertices, dtype=np.float64).reshape(-1, 3)
        tris = np.asarray(triangles, dtype=np.int32).reshape(-1, 3)
        local = world_to_local(T_world, rest)
        rewrite_mesh_topology(prim, local, tris)
        return cls(
            side=side,
            mesh_prim=prim,
            T_world_mesh=T_world,
            n_vertices=len(rest),
        )

    def update(self, world_vertices: NDArray[np.floating[Any]]) -> None:
        """Publish one frame of world-space UIPC surface points."""
        points = np.asarray(world_vertices, dtype=np.float64).reshape(-1, 3)
        if len(points) != self.n_vertices:
            raise RuntimeError(
                f"gelpad {self.side!r} vertex count changed from "
                f"{self.n_vertices} to {len(points)}"
            )
        if not np.isfinite(points).all():
            raise RuntimeError(f"gelpad {self.side!r} vertices are not finite")
        _set_points(
            UsdGeom.Mesh(self.mesh_prim),
            world_to_local(self.T_world_mesh, points),
        )
